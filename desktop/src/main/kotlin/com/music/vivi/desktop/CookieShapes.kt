package com.music.vivi.desktop

import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.geometry.Rect
import androidx.compose.ui.geometry.Size
import androidx.compose.ui.graphics.Outline
import androidx.compose.ui.graphics.Path
import androidx.compose.ui.graphics.PathOperation
import androidx.compose.ui.graphics.Shape
import androidx.compose.ui.unit.Density
import androidx.compose.ui.unit.LayoutDirection
import kotlin.math.PI
import kotlin.math.cos
import kotlin.math.hypot
import kotlin.math.max
import kotlin.math.min
import kotlin.math.sin
import kotlin.math.tan

/**
 * The Material 3 Expressive shape library, as far as the DE uses it.
 *
 * The three shapes are the library's own family (<https://m3.material.io/styles/shape>),
 * not a variation of the corner scale: a *cookie* is a regular polygon whose
 * corners are rounded, and a *clover* is four discs met at the centre. They are
 * the shapes the app gives the things that are somebody's face or a song's
 * picture, so the screen reads at a glance:
 *
 *  - [fourSided] - an artist's artwork and a song's cover in a row;
 *  - [nineSided] - a person: the Contributors list (developers and community
 *    alike) and the author of this edition;
 *  - [clover] - a Listen Together avatar.
 *
 * A cookie is drawn from the same numbers as the UI preview's `clipPath`
 * (`index.html`, generated by `.ignore/cookie_paths.py`), so the picture and the
 * app hold one shape.
 */
object CookieShapes {

    /**
     * The library's 4-sided cookie: a square with a nearly flat top, tilted 12
     * degrees. A square whose vertices point up is a diamond, which is the one
     * thing this shape is not.
     */
    val fourSided: Shape = RoundedPolygon(
        sides = 4,
        firstVertexDegrees = 45f + 12f,
        corner = 0.30f,
    )

    /** The library's 9-sided cookie: a nonagon, one vertex up, corners rounded. */
    val nineSided: Shape = RoundedPolygon(
        sides = 9,
        firstVertexDegrees = 0f,
        corner = 0.52f,
    )

    /** The library's 4-leaf clover: four discs, one per side, met in the middle. */
    val clover: Shape = FourLeafClover
}

/**
 * A regular polygon with rounded corners, fitted to the box it is given.
 *
 * [firstVertexDegrees] is where the first vertex sits, clockwise from 12
 * o'clock, which is what decides whether the shape reads as a cookie or as a
 * diamond. Each corner is a quadratic whose tangents are the radius the
 * polygon's own side asks for, so one [corner] fraction reads the same on a
 * square and on a nonagon. The turned shape is then scaled to fit the box
 * keeping its proportions: a square tilted 12 degrees is wider than the circle
 * it came from, and letting the box clip it would eat the corners the shape
 * exists for.
 */
private class RoundedPolygon(
    private val sides: Int,
    private val firstVertexDegrees: Float,
    private val corner: Float,
) : Shape {

    override fun createOutline(size: Size, layoutDirection: LayoutDirection, density: Density): Outline {
        if (size.width <= 0f || size.height <= 0f) return Outline.Generic(Path())

        val vertices = (0 until sides).map { index ->
            val angle = (firstVertexDegrees + 360f * index / sides - 90f) * PI.toFloat() / 180f
            Offset(cos(angle), sin(angle))
        }
        val side = hypot(vertices[0].x - vertices[1].x, vertices[0].y - vertices[1].y)
        // The tangent a corner of radius r takes on a regular polygon's interior
        // angle: t = r / tan(interior / 2), with r as a fraction of the side.
        val interior = PI.toFloat() * (sides - 2) / sides
        val tangent = (side * corner) / tan(interior / 2f)

        val corners = vertices.mapIndexed { index, vertex ->
            Triple(
                towards(vertex, vertices[(index + sides - 1) % sides], tangent),
                vertex,
                towards(vertex, vertices[(index + 1) % sides], tangent),
            )
        }

        val left = corners.minOf { minOf(it.first.x, it.second.x, it.third.x) }
        val right = corners.maxOf { maxOf(it.first.x, it.second.x, it.third.x) }
        val top = corners.minOf { minOf(it.first.y, it.second.y, it.third.y) }
        val bottom = corners.maxOf { maxOf(it.first.y, it.second.y, it.third.y) }
        val scale = min(size.width, size.height) / max(right - left, bottom - top)
        val dx = size.width / 2f - (left + right) / 2f * scale
        val dy = size.height / 2f - (top + bottom) / 2f * scale
        fun fit(point: Offset) = Offset(point.x * scale + dx, point.y * scale + dy)

        val path = Path()
        corners.forEachIndexed { index, (begin, vertex, end) ->
            val from = fit(begin)
            val control = fit(vertex)
            val to = fit(end)
            if (index == 0) path.moveTo(from.x, from.y) else path.lineTo(from.x, from.y)
            path.quadraticTo(control.x, control.y, to.x, to.y)
        }
        path.close()
        return Outline.Generic(path)
    }

    /** The point [length] along the line from [start] to [end]. */
    private fun towards(start: Offset, end: Offset, length: Float): Offset {
        val dx = end.x - start.x
        val dy = end.y - start.y
        val norm = hypot(dx, dy).takeIf { it > 0f } ?: return start
        return Offset(start.x + dx / norm * length, start.y + dy / norm * length)
    }
}

/**
 * Four discs whose centres sit inside each side of the box, so they meet in the
 * middle and the outline is the clover. The lobe is a little over a quarter of
 * the box: that is what leaves a notch between two leaves (at a third of the
 * box the discs overlap so far that the silhouette reads as one blob).
 */
private object FourLeafClover : Shape {

    override fun createOutline(size: Size, layoutDirection: LayoutDirection, density: Density): Outline {
        if (size.width <= 0f || size.height <= 0f) return Outline.Generic(Path())
        val lobe = min(size.width, size.height) * 0.27f
        val centres = listOf(
            Offset(size.width / 2f, lobe),
            Offset(size.width - lobe, size.height / 2f),
            Offset(size.width / 2f, size.height - lobe),
            Offset(lobe, size.height / 2f),
        )
        var path = disc(centres.first(), lobe)
        for (centre in centres.drop(1)) {
            val merged = Path()
            merged.op(path, disc(centre, lobe), PathOperation.Union)
            path = merged
        }
        return Outline.Generic(path)
    }

    private fun disc(centre: Offset, radius: Float): Path = Path().apply {
        addOval(
            Rect(
                offset = Offset(centre.x - radius, centre.y - radius),
                size = Size(radius * 2f, radius * 2f),
            ),
        )
    }
}
