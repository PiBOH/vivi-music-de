package com.music.vivi.desktop.data.network.github

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertFalse
import kotlin.test.assertNull
import kotlin.test.assertTrue

class ReleaseChecksumsTest {

    private val hash = "0123456789abcdef".repeat(4)
    private val other = "fedcba9876543210".repeat(4)
    private val shortHash = "0123456789abcdef".repeat(3)

    @Test
    fun readsTheTwoSpaceForm() {
        assertEquals(hash, ReleaseChecksums.expectedFor("installer.exe", "$hash  installer.exe"))
    }

    @Test
    fun readsTheBinaryMarker() {
        assertEquals(hash, ReleaseChecksums.expectedFor("installer.exe", "$hash *installer.exe"))
    }

    @Test
    fun readsTabSeparatedLines() {
        assertEquals(hash, ReleaseChecksums.expectedFor("installer.exe", "$hash\tinstaller.exe"))
    }

    @Test
    fun readsNamesWithSpacesAndPunctuation() {
        val name = "Axolotl Music (x64) - setup.exe"
        assertEquals(hash, ReleaseChecksums.expectedFor(name, "$hash  $name"))
    }

    @Test
    fun readsGnuEscapedBackslash() {
        val line = "\\" + hash + "  folder\\\\installer.exe"
        assertEquals(hash, ReleaseChecksums.expectedFor("folder\\installer.exe", line))
    }

    @Test
    fun ignoresCommentsBlankLinesAndInvalidHashes() {
        val text = """
            # generated by sha256sum
            $shortHash  short.exe
            not-a-hash  words.exe
            $hash  good.exe
        """.trimIndent()
        assertEquals(1, ReleaseChecksums.entries(text).size)
        assertEquals(hash, ReleaseChecksums.expectedFor("good.exe", text))
        assertNull(ReleaseChecksums.expectedFor("short.exe", text))
    }

    @Test
    fun returnsNullForAMissingAsset() {
        assertNull(ReleaseChecksums.expectedFor("missing.exe", "$hash  installer.exe"))
    }

    @Test
    fun keepsTheFirstLineForADuplicateName() {
        assertEquals(hash, ReleaseChecksums.expectedFor("installer.exe", "$hash  installer.exe\n$other  installer.exe"))
    }

    @Test
    fun matchesCaseInsensitivelyAndRefusesCorruption() {
        assertTrue(ReleaseChecksums.matches(hash.uppercase(), hash))
        assertFalse(ReleaseChecksums.matches(other, hash))
        assertFalse(ReleaseChecksums.matches(null, hash))
        assertFalse(ReleaseChecksums.matches(hash, null))
        assertFalse(ReleaseChecksums.matches(shortHash, shortHash))
    }
}
